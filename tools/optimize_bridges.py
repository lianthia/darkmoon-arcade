"""Goblin Bridge Architect: searches a cheap bridge for every level, starting from the reference
bridges in tests/test_bridgearchitect.lua, and writes them to tests/bridge_best.lua. The three star
mark of each level (Levels.lua, star3) is then set just above the cheapest bridge found, so three stars
are always possible.

    python tools/optimize_bridges.py [level ...] [--seeds N] [--evals N]
"""
import argparse
import json
import multiprocessing as mp
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ADDON = ROOT / "DarkmoonArcade"
OUT = ROOT / "tests" / "bridge_best.lua"


def runtime():
    from lupa import luajit21 as lupa
    lua = lupa.LuaRuntime(unpack_returned_tuples=True)
    lua.execute("ns = { AddStrings = function() end }")
    loader = lua.eval(
        "function(code, name) local f, err = loadstring(code, name); if not f then error(err) end; return f('DarkmoonArcade', ns) end"
    )
    for rel in ("Games/BridgeArchitect/Physics.lua", "Games/BridgeArchitect/Levels.lua"):
        loader((ADDON / rel).read_text(encoding="utf-8"), "@" + rel)
    # The reference bridges (the test file exports them; its own output is dropped).
    lua.execute("__print = print; print = function() end")
    lua.execute((ROOT / "tests" / "test_bridgearchitect.lua").read_text(encoding="utf-8"))
    lua.execute("print = __print")
    opt = loader((ROOT / "tools" / "optimize_bridges.lua").read_text(encoding="utf-8"), "@optimize_bridges.lua")
    return lua, opt


def solve(job):
    level_id, seed, evals = job
    lua, opt = runtime()
    res = lua.eval("""function(opt, id, seed, evals)
        local BA = ns.BridgeArchitect
        local P = BA.Physics
        for _, level in ipairs(BA.LEVELS) do
            if level.id == id then
                local b = P.NewBuild(level)
                BA_SOLUTIONS[id](b, level)
                local ref = P.Cost(b)
                local best, cost, peak, n = opt.Optimize(level, b, seed, evals)
                if not best then return { id = id, error = cost } end
                return { id = id, ref = ref, cost = cost, peak = peak, evals = n, data = opt.Serialize(best), budget = level.budget }
            end
        end
    end""")(opt, level_id, seed, evals)
    return {k: res[k] for k in res.keys()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("levels", nargs="*")
    ap.add_argument("--seeds", type=int, default=3)
    ap.add_argument("--evals", type=int, default=3000)
    args = ap.parse_args()
    lua, _ = runtime()
    all_ids = list(lua.eval("function() local t = {} for _, l in ipairs(ns.BridgeArchitect.LEVELS) do t[#t+1] = l.id end return t end")().values())
    ids = args.levels or all_ids
    jobs = [(i, seed, args.evals) for i in ids for seed in range(1, args.seeds + 1)]
    with mp.Pool(min(len(jobs), max(1, mp.cpu_count() - 2))) as pool:
        results = pool.map(solve, jobs)
    best = {}
    for r in results:
        if "error" in r:
            print("ERROR", r["id"], r["error"])
            continue
        if r["id"] not in best or r["cost"] < best[r["id"]]["cost"]:
            best[r["id"]] = r
    # Keep earlier results for levels not run this time (or when they were cheaper).
    old = {}
    cache = OUT.with_suffix(".json")
    if cache.exists():
        old = json.loads(cache.read_text(encoding="utf-8"))
    for k, v in old.items():
        if k not in best or v["cost"] < best[k]["cost"]:
            best[k] = v
    cache.write_text(json.dumps(best, indent=1), encoding="utf-8")
    lines = ["-- Generated by tools/optimize_bridges.py: the cheapest bridge found for each level.",
             "-- The three star mark of a level must not be below its cost here (see test_bridgearchitect.lua).",
             "return {"]
    for i in all_ids:
        if i in best:
            r = best[i]
            lines.append(f"    {i} = {r['data']},")
            print(f"{i:10s} ref {r['ref']:5d}  best {r['cost']:5d}  ({r['cost'] / r['budget']:.2f} of budget {r['budget']})  peak {r['peak']:.2f}")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
