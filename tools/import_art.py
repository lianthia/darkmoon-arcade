"""Converts the hand-made artwork in art/ into game textures: python tools/import_art.py"""
import pathlib

from PIL import Image, ImageDraw, ImageFilter

ROOT = pathlib.Path(__file__).resolve().parent.parent
MEDIA = ROOT / "DarkmoonArcade" / "media"


# The arcade's logo (art/darkmoon_logo.png, drawn by hand with a transparent background) at the top
# of a 512x256 texture (512x172 used); UI/Window.lua shows that part in the header.
LOGO_W = 512


def arcade_logo():
    src = Image.open(ROOT / "art" / "darkmoon_logo.png").convert("RGBA")
    src = src.crop(src.getbbox())
    h = round(LOGO_W * src.height / src.width)
    canvas = Image.new("RGBA", (LOGO_W, 256), (0, 0, 0, 0))
    canvas.paste(src.resize((LOGO_W, h), Image.LANCZOS), (0, 0))
    canvas.save(MEDIA / "logo.tga")
    print("arcade logo", LOGO_W, "x", h)


def moon_icon():
    """The hand-drawn moon (art/darkmoon_icon.png, on its dark square) cut to a disc: the minimap
    button, the addon list and the Darkmoon medal of Flappy Griffin."""
    src = Image.open(ROOT / "art" / "darkmoon_icon.png").convert("RGBA")
    w, h = src.size
    ss = 4
    mask = Image.new("L", (w * ss, h * ss), 0)
    r = min(w, h) / 2 * ss - ss
    cx, cy = w * ss / 2, h * ss / 2
    ImageDraw.Draw(mask).ellipse([cx - r, cy - r, cx + r, cy + r], fill=255)
    src.putalpha(mask.resize((w, h), Image.LANCZOS))
    src.resize((64, 64), Image.LANCZOS).save(MEDIA / "icon.tga")
    src.resize((128, 128), Image.LANCZOS).save(MEDIA / "portrait.tga")


def mercenaries_logo():
    """The Mercenaries title (already cut out), 960 wide with 32 px room all round at the top of a
    1024x512 texture, plus a matching soft dark halo that lifts it off busy backgrounds."""
    src = Image.open(ROOT / "art" / "mercenaries_logo.webp").convert("RGBA")
    src = src.crop(src.getbbox())
    h = round(960 * src.height / src.width)
    canvas = Image.new("RGBA", (1024, 512), (0, 0, 0, 0))
    canvas.paste(src.resize((960, h), Image.LANCZOS), (32, 32))
    canvas.save(MEDIA / "mercs" / "logo.tga")
    alpha = canvas.split()[3].filter(ImageFilter.MaxFilter(15)).filter(ImageFilter.GaussianBlur(12))
    alpha = alpha.point(lambda v: min(255, int(v * 2.4)))
    halo = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
    halo.putalpha(alpha)
    halo.save(MEDIA / "mercs" / "logo_shadow.tga")
    print("mercenaries logo used height", h + 64)


LAUNCHER = MEDIA / "launcher"


def launcher_icons():
    """The launcher's icons (art/launcher/icons, exported from Figma at 4x, one file per state) packed
    into one sheet, plus UI/IconAtlas.lua with each icon's place and size in UI units (pixels / 4)."""
    import re
    src = ROOT / "art" / "launcher" / "icons"
    icons = []
    for path in sorted(src.glob("*.png")):
        m = re.match(r"(.+?)(?:-icon|-button)? state=(\w+)(?:, active=(\w+))?$", path.stem)
        name, state, active = m.group(1), m.group(2), m.group(3) == "true"
        key = name.replace("-", "_") + ("_active" if active else "") + ("_hover" if state == "hover" else "")
        icons.append((key, Image.open(path).convert("RGBA")))
    # Shelf packing, tallest first, with a 2 px gap so neighbours never bleed into each other.
    sheet_w, sheet_h, gap = 1024, 512, 2
    icons.sort(key=lambda item: (-item[1].height, item[0]))
    sheet = Image.new("RGBA", (sheet_w, sheet_h), (0, 0, 0, 0))
    x = y = shelf = 0
    places = []
    for key, img in icons:
        if x + img.width > sheet_w:
            x, y, shelf = 0, y + shelf + gap, 0
        assert y + img.height <= sheet_h, "icon sheet full"
        sheet.paste(img, (x, y))
        places.append((key, x, y, img.width, img.height))
        x += img.width + gap
        shelf = max(shelf, img.height)
    LAUNCHER.mkdir(exist_ok=True)
    sheet.save(LAUNCHER / "icons.tga")
    lines = ["-- Generated by tools/import_art.py: the launcher icons' places on media/launcher/icons.tga",
             "-- (left, right, top, bottom as texture coordinates) and their size in UI units.", "",
             "local _, ns = ...", "", "ns.IconAtlas = {"]
    for key, px, py, w, h in sorted(places):
        lines.append(f"    {key} = {{ {px / sheet_w:.6f}, {(px + w) / sheet_w:.6f}, {py / sheet_h:.6f}, "
                     f"{(py + h) / sheet_h:.6f}, {w / 4:g}, {h / 4:g} }},")
    lines.append("}")
    (ROOT / "DarkmoonArcade" / "UI" / "IconAtlas.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("launcher icons", len(places))


def rounded_shapes():
    """White rounded shapes for nine-slice panels: a filled square, its inverse (to cut round corners
    out of pictures) and a 1 px ring. Corners have a 24 px radius in 64 px, drawn at 8x and scaled
    down for smooth edges; at a radius of 8 units the ring is 1 unit wide."""
    size, radius, stroke, ss = 64, 24, 3, 8

    def shape(inset):
        big = Image.new("L", (size * ss, size * ss), 0)
        r = (radius - inset) * ss
        o = inset * ss
        ImageDraw.Draw(big).rounded_rectangle([o, o, size * ss - 1 - o, size * ss - 1 - o], radius=r, fill=255)
        return big.resize((size, size), Image.LANCZOS)

    fill = shape(0)
    inner = shape(stroke)
    for name, alpha in (("round", fill), ("round_inv", fill.point(lambda v: 255 - v)),
                        ("ring", Image.fromarray(__import__("numpy").clip(
                            __import__("numpy").asarray(fill, dtype=int) - __import__("numpy").asarray(inner, dtype=int),
                            0, 255).astype("uint8")))):
        img = Image.new("RGBA", (size, size), (255, 255, 255, 0))
        img.putalpha(alpha)
        img.save(LAUNCHER / f"{name}.tga")
    print("rounded shapes")


def mercenaries_key_art():
    """The Mercenaries key art for the launcher's spotlight, cards and thumbnail: 910x512 at the left of a
    1024x512 texture (the right 114 px stay empty)."""
    src = Image.open(ROOT / "art" / "launcher" / "mercenaries_key.png").convert("RGB")
    canvas = Image.new("RGB", (1024, 512), (20, 12, 29))
    w = round(512 * src.width / src.height)
    canvas.paste(src.resize((w, 512), Image.LANCZOS), (0, 0))
    canvas.save(LAUNCHER / "mercenaries.tga")
    print("mercenaries key art used width", w)


# The games' small pictures in the launcher's navigation, cut exactly as in the Figma design:
# Mercenaries from its key art, the others from the main menu's card pictures
# (art/launcher/thumbs_source.png, 2048 wide, the design's 448-unit artwork; top offset per game).
THUMB_ORDER = ["mercenaries", "spellbounce", "darkmoondeck", "murlocblast", "jewelsofuldum", "flappygriffin",
               "goblinslots"]
THUMB_TOPS = {"spellbounce": 45.58, "darkmoondeck": 84.33, "murlocblast": 123.3, "jewelsofuldum": 162.06,
              "flappygriffin": 201.03, "goblinslots": 239.78}


def launcher_thumbs():
    src = Image.open(ROOT / "art" / "launcher" / "thumbs_source.png").convert("RGB")
    key = Image.open(ROOT / "art" / "launcher" / "mercenaries_key.png").convert("RGB")
    k = src.width / 448
    sheet = Image.new("RGB", (512, 64))
    for i, game in enumerate(THUMB_ORDER):
        if game == "mercenaries":
            # The design's 279x201 box over the key art, cropped to cover, shows Thrall's face.
            s = key.height / 201
            left = (key.width - 279 * s) / 2
            box = (left + 131 * s, 64 * s, left + 159 * s, 92 * s)
        else:
            top = THUMB_TOPS[game]
            box = (303.18 * k, top * k, 331.18 * k, (top + 28) * k)
        cell = src if game != "mercenaries" else key
        sheet.paste(cell.crop(tuple(round(v) for v in box)).resize((64, 64), Image.LANCZOS), (i * 64, 0))
    sheet.save(LAUNCHER / "thumbs.tga")
    print("launcher thumbs", len(THUMB_ORDER))


def mercenaries_camp():
    """The Mercenaries camp (art/mercenaries_camp.png, 1672x941): cut to the camp's 920:560 and scaled
    to 1024 high at the left of a 2048x1024 texture (Games/Mercenaries/Camp.lua)."""
    src = Image.open(ROOT / "art" / "mercenaries_camp.png").convert("RGB")
    w = round(src.height * 920 / 560)
    left = (src.width - w) // 2
    cut = src.crop((left, 0, left + w, src.height))
    scaled = cut.resize((round(1024 * w / src.height), 1024), Image.LANCZOS)
    canvas = Image.new("RGB", (2048, 1024), (0, 0, 0))
    canvas.paste(scaled, (0, 0))
    canvas.save(MEDIA / "mercs" / "camp.tga")
    print("mercenaries camp used width", scaled.width, "crop left", left)


def mercenaries_roles():
    """The role tabs of the collection (art/mercenaries_roles/<role>-<state>.png, 492x492 from Figma):
    128x128 each, media/mercs/roletab_<role>_<state>.tga."""
    for path in sorted((ROOT / "art" / "mercenaries_roles").glob("*.png")):
        role, state = path.stem.split("-")
        Image.open(path).convert("RGBA").resize((128, 128), Image.LANCZOS).save(
            MEDIA / "mercs" / f"roletab_{role}_{state}.tga")
    print("mercenaries role tabs")


def zone_maps():
    """Forever's own zone maps for retail, which lacks them (art/maps/<zone>.png, 1002x668), cut like the
    client's maps into 4x3 tiles of 256x256 (media/maps/<zone>_<n>.tga, uncompressed, which WoW
    surely reads). Games/Mercenaries/Retail.lua shows them."""
    target = MEDIA / "maps"
    target.mkdir(exist_ok=True)
    for old in target.glob("*.tga"):
        old.unlink()
    for path in sorted((ROOT / "art" / "maps").glob("*.png")):
        # The parchment's rounded corners on the window's dark instead of transparency.
        src = Image.new("RGB", (1024, 768), (11, 7, 15))
        art = Image.open(path).convert("RGBA")
        src.paste(art, (0, 0), art)
        for i in range(12):
            row, col = divmod(i, 4)
            src.crop((col * 256, row * 256, col * 256 + 256, row * 256 + 256)).save(target / f"{path.stem}_{i + 1}.tga")
    print("zone maps", len(list(target.glob("*.tga"))))


