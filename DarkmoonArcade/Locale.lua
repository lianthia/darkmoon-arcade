local CLIENT_LANGUAGE = {
    enGB = "enUS", esMX = "esES", zhTW = "zhCN", ptBR = "enUS", itIT = "enUS", koKR = "enUS",
}

local THOUSANDS = { deDE = ".", esES = ".", frFR = " ", ruRU = " " }

local active = strings.enUS
ns.language = "enUS"
ns.L = setmetatable({}, {
    __index = function(_, k)
        return active[k] or strings.enUS[k] or k
    end,
})

function ns.ResolveLanguage(setting)
    if setting and strings[setting] then return setting end
    local client = GetLocale()
    client = CLIENT_LANGUAGE[client] or client
    return strings[client] and client or "enUS"
end

function ns.SetLanguage(setting)
    ns.language = ns.ResolveLanguage(setting)
    active = strings[ns.language]
end

function ns.FormatNumber(n)
    local s = tostring(math.floor(n))
    local sep = THOUSANDS[ns.language] or ","
    local formatted = s:reverse():gsub("(%d%d%d)", "%1" .. sep):reverse()
    if formatted:sub(1, #sep) == sep then formatted = formatted:sub(#sep + 1) end
    return formatted
end

function ns.FormatTime(seconds)
    seconds = math.max(0, math.floor(seconds + 0.5))
    return ("%d:%02d"):format(math.floor(seconds / 60), seconds % 60)
end
